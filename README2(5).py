# Запрашиваем строку у пользователя
s = input("Введите строку: ")

# Находим индекс первого и последнего вхождения буквы 'h'
first_h = s.find("h")
last_h = s.rfind("h")

# Выделяем подстроку МЕЖДУ первым и последним 'h'
# Разворачиваем её с помощью среза [::-1]
reversed_part = s[first_h + 1 : last_h][::-1]

# Выводим результат
print(f"Развёрнутая последовательность между первым и последним h: {reversed_part}")
